// Includo le direttive

#include <iostream>
using namespace std;

// Funzione principale(main) 

int main() {

    // Variabile da decrementare

    int count = 10;

    // Ciclo for decremento

    for (count; count >= 0; count--) {

        // Stampa decremento

        cout << count << endl;

    }

    return 0;

}